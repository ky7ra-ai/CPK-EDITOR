#!/usr/bin/env python3
"""Generates the app's shuriken artwork from one geometry definition.

Writes: launcher vector drawables (adaptive icon + monochrome), legacy PNG launcher icons,
and ShurikenArt.kt (the same path data for Compose). Run from the repo root:  python3 tools/gen_shuriken.py
"""
import math, os, sys
from PIL import Image, ImageDraw

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RES = os.path.join(ROOT, "app/src/main/res")
KT = os.path.join(ROOT, "app/src/main/kotlin/com/ky7ra/cpkeditor/ui/ShurikenArt.kt")

VIEW = 108.0
C = (54.0, 54.0)
TIP = 36.0        # tip radius
VALLEY = 16.0     # radius of the notch between two blades
TWIST = 12.0      # degrees: shifts the notches so the star looks like it is spinning
BOW = 0.26        # how far the edges bend inward (concave blades)
HUB = 9.6
HOLE = 3.8

def pol(r, deg):
    a = math.radians(deg)
    return (C[0] + r * math.cos(a), C[1] + r * math.sin(a))

def lerp(a, b, t):
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)

def tip(k): return pol(TIP, -90 + 90 * k)
def valley(k): return pol(VALLEY, -90 + 90 * k + 45 + TWIST)   # notch after blade k

def edge(p, q):
    """Cubic from p to q bowed toward the centre: returns (c1, c2, q)."""
    c1 = lerp(lerp(p, q, 0.33), C, BOW)
    c2 = lerp(lerp(p, q, 0.72), C, BOW * 0.55)
    return (c1, c2, q)

def f(p): return "%.2f,%.2f" % p

def cubic(c): return "C%s %s %s" % (f(c[0]), f(c[1]), f(c[2]))

def circle(r, cx=C[0], cy=C[1]):
    return "M%.2f,%.2f a%.2f,%.2f 0 1,0 %.2f,0 a%.2f,%.2f 0 1,0 %.2f,0 z" % (cx - r, cy, r, r, 2 * r, r, r, -2 * r)

# Each blade k has a lit side (tip -> next notch) and a shaded side (previous notch -> tip).
def lit(k):
    t, v = tip(k), valley(k)
    return "M%s %s L%s Z" % (f(t), cubic(edge(t, v)), f(C))

def shade(k):
    v, t = valley((k - 1) % 4), tip(k)
    # draw the shaded edge from the notch up to the tip, mirrored bow so both sides are concave
    c1, c2, _ = edge(t, v)
    return "M%s L%s %s Z" % (f(C), f(v), cubic((c2, c1, t)))

def silhouette():
    parts = ["M%s" % f(tip(0))]
    for k in range(4):
        v = valley(k)
        parts.append(cubic(edge(tip(k), v)))
        t2 = tip((k + 1) % 4)
        c1, c2, _ = edge(t2, v)
        parts.append(cubic((c2, c1, t2)))
    parts.append("Z")
    return " ".join(parts)

LIT = " ".join(lit(k) for k in range(4))
SHADE = " ".join(shade(k) for k in range(4))
SIL = silhouette()
HUB_P = circle(HUB)
HOLE_P = circle(HOLE)
SIL_HOLE = SIL + " " + circle(HOLE)   # used with even-odd fill

BG = "#141210"
ORANGE = "#FF5A36"
STEEL_LIGHT = "#F4F4F4"
STEEL_DARK = "#B4B9C2"

def vector(w, h, body, extra=""):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="%ddp"\n    android:height="%ddp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n%s</vector>\n' % (w, h, body))

def path(data, fill, extra=""):
    return '    <path\n        android:fillColor="%s"%s\n        android:pathData="%s" />\n' % (fill, extra, data)

def write(p, s):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w").write(s)

# --- vector drawables ---------------------------------------------------------------------
write(RES + "/drawable/ic_launcher_background.xml", vector(108, 108,
      path("M0,0h108v108h-108z", BG) + path(circle(41), ORANGE, '\n        android:fillAlpha="0.12"')))
write(RES + "/drawable/ic_launcher_foreground.xml", vector(108, 108,
      path(SIL, STEEL_DARK) + path(LIT, STEEL_LIGHT) + path(HUB_P, ORANGE) + path(HOLE_P, BG)))
write(RES + "/drawable/ic_launcher_monochrome.xml", vector(108, 108,
      path(SIL_HOLE, "#000000", '\n        android:fillType="evenOdd"')))
adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n</adaptive-icon>\n')
write(RES + "/mipmap-anydpi-v26/ic_launcher.xml", adaptive)
write(RES + "/mipmap-anydpi-v26/ic_launcher_round.xml", adaptive)

# --- Kotlin path data ---------------------------------------------------------------------
write(KT, '''package com.ky7ra.cpkeditor.ui

/**
 * Original shuriken artwork. GENERATED by tools/gen_shuriken.py - edit the script, not this file.
 * All paths share one 108 x 108 viewport, the same one the launcher icon uses.
 */
object ShurikenArt {
    const val VIEWPORT = %.1ff
    const val SILHOUETTE = "%s"
    const val LIT_FACETS = "%s"
    const val HUB = "%s"
    const val HOLE = "%s"
    const val TIP_RADIUS = %.1ff
}
''' % (VIEW, SIL, LIT, HUB_P, HOLE_P, TIP))

# --- raster preview + legacy PNG icons -----------------------------------------------------
def bezier(p0, p1, p2, p3, n=24):
    out = []
    for i in range(1, n + 1):
        t = i / n; u = 1 - t
        out.append((u**3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t**3 * p3[0],
                    u**3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t**3 * p3[1]))
    return out

def sil_points():
    pts = [tip(0)]
    for k in range(4):
        v = valley(k)
        pts += bezier(tip(k), *edge(tip(k), v))
        t2 = tip((k + 1) % 4)
        c1, c2, _ = edge(t2, v)
        pts += bezier(v, c2, c1, t2)
    return pts

def lit_polys():
    polys = []
    for k in range(4):
        t, v = tip(k), valley(k)
        polys.append([t] + bezier(t, *edge(t, v)) + [C])
    return polys

def render(size, rounded):
    s = 4
    N = size * s
    k = N / VIEW
    img = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    mask = Image.new("L", (N, N), 0)
    md = ImageDraw.Draw(mask)
    if rounded == "round":
        md.ellipse((0, 0, N - 1, N - 1), fill=255)
    else:
        md.rounded_rectangle((0, 0, N - 1, N - 1), radius=int(N * 0.22), fill=255)
    bg = Image.new("RGBA", (N, N), BG)
    ov = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    ImageDraw.Draw(ov).ellipse(((54 - 41) * k, (54 - 41) * k, (54 + 41) * k, (54 + 41) * k), fill=(255, 90, 54, 31))
    bg = Image.alpha_composite(bg, ov)
    img.paste(bg, (0, 0), mask)
    d = ImageDraw.Draw(img)
    sc = lambda pts: [(x * k, y * k) for x, y in pts]
    d.polygon(sc(sil_points()), fill=STEEL_DARK)
    for poly in lit_polys():
        d.polygon(sc(poly), fill=STEEL_LIGHT)
    d.ellipse(((54 - HUB) * k, (54 - HUB) * k, (54 + HUB) * k, (54 + HUB) * k), fill=ORANGE)
    d.ellipse(((54 - HOLE) * k, (54 - HOLE) * k, (54 + HOLE) * k, (54 + HOLE) * k), fill=BG)
    return img.resize((size, size), Image.LANCZOS)

for folder, px in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
    os.makedirs(RES + "/mipmap-" + folder, exist_ok=True)
    render(px, "square").save(RES + "/mipmap-%s/ic_launcher.png" % folder)
    render(px, "round").save(RES + "/mipmap-%s/ic_launcher_round.png" % folder)

if len(sys.argv) > 1:
    render(512, "square").save(sys.argv[1])
print("ok")
